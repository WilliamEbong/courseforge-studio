// Review Quiz. The learner steps through the submitted attempt read-only and returns to the results slide
// nothing about the result changes. Synthetic courses only.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { emptyCourse, validate } from '../../packages/schema/index.js';
import { applyAll, describe } from '../../packages/core/index.js';
import { createRuntime, seededRng } from '../../packages/runtime/index.js';
import { importStory } from '../../packages/import-story/index.js';
import { pkg, ID } from '../fixtures/synthetic/story-builder.js';

const ch = (...list) => list.map(([id, label, correct]) => ({ id, label, ...(correct ? { correct: true } : {}) }));
const build = (cmds) => {
  const r = applyAll(emptyCourse({ id: 'rv', title: 'Review' }), cmds, { rng: seededRng(3) });
  assert.ok(r.ok, JSON.stringify(r.errors));
  return r.doc;
};
// Flow: intro, mc, mr, a draw of 2 from b1..b3, tf, fill, matching, sequence, results (generated by quiz.addResults).
const COURSE = [
  { cmd: 'slide.add', args: { id: 's-intro', title: 'Intro' } },
  { cmd: 'slide.add', args: { id: 's-mc', title: 'MC', question: { type: 'mc', prompt: 'Pick yes', shuffle: false, choices: ch(['a', 'No'], ['b', 'Yes', true]) } } },
  { cmd: 'slide.add', args: { id: 's-mr', title: 'MR', question: { type: 'mr', prompt: 'Pick one and three', shuffle: false, choices: ch(['a', 'One', true], ['b', 'Two'], ['c', 'Three', true]) } } },
  { cmd: 'bank.add', args: { id: 'bk-1', title: 'Bank' } },
  ...[1, 2, 3].map((k) => ({ cmd: 'slide.add', args: { id: `s-b${k}`, bank: 'bk-1', title: `Bank ${k}`, question: { type: 'mc', prompt: `Bank ${k}`, shuffle: false, choices: ch(['a', `Right ${k}`, true], ['b', `Wrong ${k}`]) } } })),
  { cmd: 'draw.add', args: { id: 's-draw', bank: 'bk-1', count: 2 } },
  { cmd: 'slide.add', args: { id: 's-tf', title: 'TF', question: { type: 'tf', prompt: 'Sky is blue', shuffle: false, choices: ch(['t', 'True', true], ['f', 'False']) } } },
  { cmd: 'slide.add', args: { id: 's-fill', title: 'Fill', question: { type: 'fill', prompt: 'Type teal', answers: ['teal', 'teal blue'] } } },
  { cmd: 'slide.add', args: { id: 's-match', title: 'Match', question: { type: 'matching', prompt: 'Match them', shuffle: false, choices: ch(['x', 'Ex'], ['y', 'Why']), rows: [{ id: 'r1', label: 'Row 1', choice: 'x' }, { id: 'r2', label: 'Row 2', choice: 'y' }] } } },
  { cmd: 'slide.add', args: { id: 's-seq', title: 'Seq', question: { type: 'sequence', prompt: 'Order them', shuffle: false, choices: ch(['one', 'First'], ['two', 'Second'], ['three', 'Third']) } } },
  { cmd: 'quiz.add', args: { id: 'qz', title: 'Final', questions: ['s-mc', 's-mr', 's-draw', 's-tf', 's-fill', 's-match', 's-seq'] } },
  { cmd: 'quiz.addResults', args: { quiz: 'qz', id: 's-res', track: true } },
];
const REVIEWED = ['s-mc', 's-mr', 's-b2', 's-b1', 's-tf', 's-fill', 's-match', 's-seq'];
/** rng: the draw takes b2 then b1 (pick order, not bank order); later values serve a retry's new draw. */
const rngOf = () => { const v = [0.5, 0, 0.9, 0.9]; return () => (v.length ? v.shift() : 0); };
function start(doc = build(COURSE), rec = []) {
  const lms = { init: () => null, status: (s) => rec.push(`status ${s}`), score: (x) => rec.push(`score ${x.raw}`), interaction: (r) => rec.push(`ix ${r.id} ${r.result}`), save() {} };
  const rt = createRuntime(doc, { rng: rngOf(), lms });
  rt.start();
  return rt;
}
// Answers: mc wrong, mr right, b2 right, b1 wrong, tf right, fill right (case-insensitive), matching half wrong, sequence wrong.
const ANSWERS = {
  's-mc': [{ type: 'choose', choice: 'a' }], 's-mr': [{ type: 'choose', choice: 'a' }, { type: 'choose', choice: 'c' }],
  's-b2': [{ type: 'choose', choice: 'a' }], 's-b1': [{ type: 'choose', choice: 'b' }], 's-tf': [{ type: 'choose', choice: 't' }],
  's-fill': [{ type: 'input', answer: true, text: 'TEAL' }], 's-match': [{ type: 'match', row: 'r1', choice: 'x' }, { type: 'match', row: 'r2', choice: 'x' }],
  's-seq': [{ type: 'order', choice: 'three', index: 0 }],
};
function finish(rt) {
  rt.dispatch({ type: 'next' });
  while (ANSWERS[rt.state.slide]) for (const e of [...ANSWERS[rt.state.slide], { type: 'submit' }, { type: 'continue' }]) rt.dispatch(e);
  assert.equal(rt.state.slide, 's-res');
  return rt;
}

// ---------------- commands ----------------
test('quiz.addResults adds a Review quiz button on the base layer (shown after pass and fail); review:false leaves it out', () => {
  const doc = build(COURSE);
  const res = doc.slides.find((s) => s.id === 's-res');
  const btn = res.objects.find((o) => o.id === 's-res-review');
  assert.deepEqual([btn.type, btn.text], ['button', 'Review quiz']);
  const t = res.triggers.find((x) => x.id === 's-res-review-t');
  assert.deepEqual([t.on, t.do], [{ event: 'click', target: 's-res-review' }, [{ action: 'reviewQuiz', quiz: 'qz' }]]);
  const retry = res.layers[1].objects.find((o) => o.id === 's-res-retry');
  assert.ok(btn.y + btn.h <= retry.y, 'Review sits above Retry, so both show after a fail and the tab order follows the layout');
  assert.deepEqual(validate(doc), []);
  const plain = build([...COURSE.slice(0, -1), { cmd: 'quiz.addResults', args: { quiz: 'qz', id: 's-res', review: false } }]);
  assert.equal(plain.slides.find((s) => s.id === 's-res').objects.some((o) => o.id === 's-res-review'), false);
  assert.match(describe(doc), /s-res-review-t: click s-res-review → reviewQuiz qz/);
});

test('quiz.set {review} removes and re-adds the button; refused without a results slide; validate checks the quiz', () => {
  const doc = build(COURSE);
  let r = applyAll(doc, [{ cmd: 'quiz.set', args: { id: 'qz', review: false } }]);
  assert.ok(r.ok, JSON.stringify(r.errors));
  const res = (d) => d.slides.find((s) => s.id === 's-res');
  assert.equal(res(r.doc).objects.some((o) => o.id === 's-res-review'), false);
  assert.equal(res(r.doc).triggers.some((t) => t.do.some((a) => a.action === 'reviewQuiz')), false);
  r = applyAll(r.doc, [{ cmd: 'quiz.set', args: { id: 'qz', review: true } }, { cmd: 'quiz.set', args: { id: 'qz', review: true } }]);
  assert.ok(r.ok, JSON.stringify(r.errors));
  assert.equal(res(r.doc).objects.filter((o) => o.id === 's-res-review').length, 1, 'adding twice keeps one button');
  assert.deepEqual(r.doc, doc, 'off then on restores the generated slide');
  const bare = build([...COURSE.slice(0, -1)]);
  const e = applyAll(bare, [{ cmd: 'quiz.set', args: { id: 'qz', review: true } }]);
  assert.equal(e.ok, false);
  assert.match(e.errors[0].message, /no results slide/);
  assert.match(e.errors[0].hint, /quiz.addResults/);
  const bad = structuredClone(doc);
  res(bad).triggers.find((t) => t.id === 's-res-review-t').do[0].quiz = 'qz-nope';
  const errs = validate(bad);
  assert.equal(errs[0].code, 'ref');
  assert.match(errs[0].hint, /quizzes: qz/);
});

// ---------------- runtime ----------------
test('review visits the attempt in the order taken (drawn bank slides as drawn), then Next returns to the results slide', () => {
  const rt = finish(start());
  assert.equal(rt.view().review, null);
  rt.dispatch({ type: 'click', target: 's-res-review' });
  assert.ok(rt.trace.includes(`review qz ${REVIEWED.join(',')}`));
  const seen = [rt.state.slide];
  assert.deepEqual(rt.view().review, { quiz: 'qz', title: 'Final', index: 0, count: 8 });
  assert.deepEqual(rt.view().nav, { prev: false, next: true, submit: false });
  rt.dispatch({ type: 'prev' });
  assert.equal(rt.state.slide, 's-mc', 'Prev on the first reviewed question goes nowhere');
  for (let i = 1; i < REVIEWED.length; i++) { rt.dispatch({ type: 'next' }); seen.push(rt.state.slide); }
  assert.deepEqual(seen, REVIEWED);
  rt.dispatch({ type: 'prev' });
  assert.equal(rt.state.slide, 's-match', 'Prev walks back along the review list');
  rt.dispatch({ type: 'next' }).dispatch({ type: 'next' });
  assert.equal(rt.state.slide, 's-res');
  assert.equal(rt.view().review, null);
  assert.ok(rt.trace.includes('review end qz'));
});

test('answers are read-only in review: choose, input, match, order, submit and the submit action are ignored', () => {
  const doc = build([...COURSE, { cmd: 'trigger.add', args: { slide: 's-mc', on: { event: 'key', key: 's' }, do: [{ action: 'submit' }] } }]);
  const rt = finish(start(doc));
  rt.dispatch({ type: 'click', target: 's-res-review' });
  const before = structuredClone(rt.state.q);
  rt.dispatch({ type: 'choose', choice: 'b' }).dispatch({ type: 'submit' }).dispatch({ type: 'key', key: 's' });
  rt.dispatch({ type: 'menu', slide: 's-fill' }).dispatch({ type: 'input', answer: true, text: 'nope' });
  rt.dispatch({ type: 'menu', slide: 's-match' }).dispatch({ type: 'match', row: 'r2', choice: 'y' });
  rt.dispatch({ type: 'menu', slide: 's-seq' }).dispatch({ type: 'order', choice: 'one', index: 0 });
  assert.deepEqual(rt.state.q, before);
  assert.equal(rt.state.feedback, null);
  assert.ok(rt.view().review, 'menu jumps between reviewed questions stay in review');
  for (const ev of ['choose', 'submit', 'input', 'match', 'order']) assert.ok(rt.trace.includes(`ignored ${ev} in review`), ev);
});

test('review changes no score, status, interaction, viewed mark, variable, quiz state or Prev history', () => {
  const rec = [];
  const rt = finish(start(build(COURSE), rec));
  assert.ok(rec.includes('status failed'));
  const n = rec.length;
  const keep = structuredClone({ vars: rt.state.vars, quiz: rt.state.quiz, viewed: rt.state.viewed, history: rt.state.history, q: rt.state.q, draws: rt.state.draws, status: rt.state.status });
  rt.dispatch({ type: 'click', target: 's-res-review' });
  for (let i = 0; i < REVIEWED.length; i++) rt.dispatch({ type: 'next' });
  assert.equal(rt.state.slide, 's-res');
  assert.deepEqual(rec.slice(n), [], 'nothing reported to the LMS');
  assert.deepEqual({ vars: rt.state.vars, quiz: rt.state.quiz, viewed: rt.state.viewed, history: rt.state.history, q: rt.state.q, draws: rt.state.draws, status: rt.state.status }, keep);
  assert.deepEqual(rt.state.layers, ['s-res-fail'], 'the results slide shows its result again');
  rt.dispatch({ type: 'prev' });
  assert.equal(rt.state.slide, 's-seq', 'Prev on the results slide goes where it went before review');
  assert.equal(rt.view().review, null);
});

test('review records per type: correct/incorrect, the learner answer and the correct answer (mc, mr, tf, fill, matching, sequence)', () => {
  const rt = finish(start());
  rt.dispatch({ type: 'click', target: 's-res-review' });
  const got = {};
  for (const sid of REVIEWED) { assert.equal(rt.state.slide, sid); got[sid] = rt.view().question.review; rt.dispatch({ type: 'next' }); }
  assert.deepEqual(got, {
    's-mc': { correct: false, answered: true, yours: ['No'], answer: ['Yes'] },
    's-mr': { correct: true, answered: true, yours: ['One', 'Three'], answer: ['One', 'Three'] },
    's-b2': { correct: true, answered: true, yours: ['Right 2'], answer: ['Right 2'] },
    's-b1': { correct: false, answered: true, yours: ['Wrong 1'], answer: ['Right 1'] },
    's-tf': { correct: true, answered: true, yours: ['True'], answer: ['True'] },
    's-fill': { correct: true, answered: true, yours: ['TEAL'], answer: ['teal', 'teal blue'] },
    's-match': { correct: false, answered: true, yours: ['Row 1: Ex', 'Row 2: Ex'], answer: ['Row 1: Ex', 'Row 2: Why'] },
    's-seq': { correct: false, answered: true, yours: ['Third', 'First', 'Second'], answer: ['First', 'Second', 'Third'] },
  });
  rt.dispatch({ type: 'menu', slide: 's-mc' });
  assert.equal(rt.view().review, null, 'the menu left review (s-mc is outside a finished review)');
  rt.dispatch({ type: 'menu', slide: 's-res' }).dispatch({ type: 'review' }); // the review event: the quiz of this results slide
  const q = rt.view().question;
  assert.deepEqual(q.choices.map((c) => [c.label, c.selected, c.correct]), [['No', true, false], ['Yes', false, true]]);
  rt.dispatch({ type: 'menu', slide: 's-match' });
  assert.deepEqual(rt.view().question.rows.map((r) => [r.id, r.selected, r.answer]), [['r1', 'x', 'x'], ['r2', 'x', 'y']]);
  rt.dispatch({ type: 'exitReview' });
  assert.equal(rt.state.slide, 's-res');
  assert.equal(rt.view().question, null);
  const fresh = start().dispatch({ type: 'next' }).view().question;
  assert.deepEqual([fresh.review, 'correct' in fresh.choices[0]], [undefined, false], 'no answers in the view outside review');
});

test('hotspot and drag-and-drop review records; a question never reached shows Not answered and gets no state', () => {
  const doc = build([
    { cmd: 'slide.add', args: { id: 's-hs', question: { type: 'hotspot', prompt: 'Click the box', areas: [{ id: 'box', x: 0, y: 0, w: 100, h: 100, correct: true }, { id: 'door', x: 500, y: 0, w: 100, h: 100 }] } } },
    { cmd: 'slide.add', args: { id: 's-dd', objects: [{ id: 'o-cup', type: 'button', text: 'Cup' }, { id: 'o-bin', type: 'shape', x: 300, text: 'Bin' }, { id: 'o-box', type: 'shape', x: 600, alt: 'Box' }], question: { type: 'dragdrop', prompt: 'Sort', items: [{ object: 'o-cup', target: 'o-bin' }], targets: [{ object: 'o-bin' }, { object: 'o-box' }] } } },
    { cmd: 'slide.add', args: { id: 's-skip', question: { type: 'mc', prompt: 'Skipped', choices: ch(['a', 'A', true], ['b', 'B']) } } },
    { cmd: 'quiz.add', args: { id: 'qz', questions: ['s-hs', 's-dd', 's-skip'] } },
    { cmd: 'quiz.addResults', args: { quiz: 'qz', id: 's-res' } },
    { cmd: 'slide.move', args: { id: 's-skip', index: 3 } }, // after the results slide: the learner never reaches it
  ]);
  const rt = createRuntime(doc, { rng: seededRng(1) });
  rt.start();
  for (const e of [{ type: 'point', x: 550, y: 50 }, { type: 'submit' }, { type: 'continue' }, { type: 'drop', item: 'o-cup', target: 'o-box' }, { type: 'submit' }, { type: 'continue' }]) rt.dispatch(e);
  assert.deepEqual([rt.state.slide, rt.state.q['s-skip']], ['s-res', undefined]);
  rt.dispatch({ type: 'click', target: 's-res-review' });
  const hs = rt.view().question;
  assert.deepEqual(hs.review, { correct: false, answered: true, yours: ['outside the correct area'], answer: ['the outlined area'] });
  assert.deepEqual(hs.areas, [{ id: 'box', shape: 'rect', x: 0, y: 0, w: 100, h: 100 }]);
  rt.dispatch({ type: 'next' });
  const dd = rt.view().question;
  assert.deepEqual(dd.review, { correct: false, answered: true, yours: ['Cup: Box'], answer: ['Cup: Bin'] });
  assert.deepEqual(dd.items, [{ object: 'o-cup', placed: 'o-box', target: 'o-bin' }]);
  rt.dispatch({ type: 'next' });
  assert.equal(rt.state.slide, 's-skip');
  assert.deepEqual(rt.view().question.review, { correct: false, answered: false, yours: [], answer: ['A'] });
  assert.equal(rt.state.q['s-skip'], undefined, 'review creates no answer state');
  assert.equal(rt.state.viewed.includes('s-skip'), false, 'and marks nothing viewed');
  rt.dispatch({ type: 'next' });
  assert.equal(rt.state.slide, 's-res', 'Next after the last reviewed question returns, even when the flow continues');
});

test('review needs a submitted quiz; resetQuiz ends review', () => {
  const rt = start(build([...COURSE, { cmd: 'trigger.add', args: { slide: 's-mc', on: { event: 'key', key: 'r' }, do: [{ action: 'resetQuiz', quiz: 'qz' }] } }]));
  rt.dispatch({ type: 'next' }).dispatch({ type: 'review', quiz: 'qz' });
  assert.equal(rt.view().review, null);
  assert.ok(rt.trace.includes('warn quiz qz not submitted'));
  finish(rt);
  rt.dispatch({ type: 'review', quiz: 'qz' });
  assert.equal(rt.state.slide, 's-mc');
  rt.dispatch({ type: 'review', quiz: 'qz-nope' });
  assert.ok(rt.trace.includes('warn no qz-nope quiz'));
  assert.ok(rt.view().review, 'a failed review request keeps the current review');
  rt.dispatch({ type: 'key', key: 'r' }); // a resetQuiz trigger on a reviewed slide
  assert.deepEqual([rt.view().review, rt.state.slide, rt.state.q['s-mc'].selected], [null, 's-mc', []]);
  rt.dispatch({ type: 'choose', choice: 'b' });
  assert.deepEqual(rt.state.q['s-mc'].selected, ['b'], 'answering works again');
});

