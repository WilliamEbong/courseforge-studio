test('snapshot/restore mid-review resumes review on the same question and keeps the list', () => {
  const doc = build(COURSE);
  let saved = null;
  const rt = createRuntime(doc, { rng: rngOf(), lms: { init: () => null, save: (s) => { saved = JSON.parse(JSON.stringify(s)); } } });
  rt.start();
  finish(rt);
  rt.dispatch({ type: 'click', target: 's-res-review' }).dispatch({ type: 'next' }).dispatch({ type: 'next' });
  assert.equal(rt.state.slide, 's-b2');
  assert.deepEqual(saved.rv, { quiz: 'qz', results: doc.scenes[0].slides.indexOf('s-res') });
  const rec = [];
  const back = createRuntime(doc, { rng: () => { throw new Error('no rng on resume'); }, lms: { init: () => saved, status: (s) => rec.push(`status ${s}`), score: (x) => rec.push(`score ${x.raw}`), interaction: (r) => rec.push(`ix ${r.id}`), save() {} } });
  back.start({ resume: true });
  assert.equal(back.state.slide, 's-b2');
  assert.deepEqual(back.view().review, { quiz: 'qz', title: 'Final', index: 2, count: 8 });
  back.dispatch({ type: 'choose', choice: 'b' });
  assert.equal(back.state.q['s-b2'].selected.join(), 'a', 'still read-only');
  back.dispatch({ type: 'next' });
  assert.equal(back.state.slide, 's-b1');
  back.dispatch({ type: 'exitReview' });
  assert.equal(back.state.slide, 's-res');
  assert.deepEqual(rec, [], 'resuming a review and returning to results preserves the reported score');
  for (const rv of [{ quiz: 'qz-nope', results: 0 }, { quiz: 'qz', results: 'x' }, 'qz', { quiz: { toString: 1 } }]) {
    const r = createRuntime(doc, { rng: seededRng(1), lms: { init: () => ({ ...saved, rv }) } });
    r.start({ resume: true });
    assert.equal(r.state.slide, 's-b2');
    assert.equal(r.view().review, null, `hostile rv ${JSON.stringify(rv)} is dropped`);
  }
});

