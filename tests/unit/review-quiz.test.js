test('review never runs the reviewed slides\' triggers: variables, completion and LMS status stay as submitted (007 #4)', () => {
  const doc = build([
    { cmd: 'var.add', args: { name: 'visits', type: 'number', initial: 0 } },
    { cmd: 'slide.add', args: { id: 's-q', title: 'Q', question: { type: 'mc', prompt: 'Pick yes', shuffle: false, choices: ch(['a', 'No'], ['b', 'Yes', true]) } } },
    { cmd: 'trigger.add', args: { slide: 's-q', on: { event: 'timelineStart' }, do: [{ action: 'setVar', var: 'visits', op: 'add', value: 1 }] } },
    { cmd: 'quiz.add', args: { id: 'qz', questions: ['s-q'], passPercent: 100 } },
    { cmd: 'quiz.addResults', args: { quiz: 'qz', id: 's-res' } },
  ]);
  const rec = [];
  const rt = start(doc, rec);
  for (const e of [{ type: 'choose', choice: 'a' }, { type: 'submit' }, { type: 'continue' }]) rt.dispatch(e);
  assert.equal(rt.state.slide, 's-res');
  const visits = rt.state.vars.visits, sent = rec.length;
  rt.dispatch({ type: 'review' });
  assert.equal(rt.state.slide, 's-q');
  assert.equal(rt.state.vars.visits, visits, 'the question slide\'s timelineStart trigger did not run in review');
  rt.dispatch({ type: 'tick', ms: 5000 });
  rt.dispatch({ type: 'exitReview' });
  assert.equal(rt.state.vars.visits, visits);
  assert.ok(!rec.slice(sent).some((x) => /^status (completed|passed)/.test(x)), `review changed the LMS status: ${rec.slice(sent)}`);
});

